def _strip_flag_row(post: str) -> str:
    lines = post.split("\n")
    if not lines:
        return post
    first = lines[0].strip().replace(" ", "")
    flag_chars = {"✅", "⚡", "️", "💣", "🔥", "🚨"}
    if first and all(ch in flag_chars for ch in first):
        return "\n".join(lines[1:]).lstrip("\n")
    return post


FEWSHOT_FOR_PRODUCER = [{**ex, "post": _strip_flag_row(ex["post"])} for ex in FEWSHOT_RAW]


def get_fewshot(archetype: str, k: int = 3) -> list[dict]:
    """k примеров нужного архетипа; добор из соседних если мало."""
    same = [ex for ex in FEWSHOT_FOR_PRODUCER if ex["archetype"] == archetype]
    if len(same) >= k:
        return same[:k]
    others = [ex for ex in FEWSHOT_FOR_PRODUCER if ex["archetype"] != archetype]
    return (same + others)[:k]


