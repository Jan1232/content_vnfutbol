def get_tone_examples(archetype=None, k=4):
    """k пар bad/good для few-shot критика; фильтр по архетипу если задан."""
    pool = TONE_REFERENCE
    if archetype:
        same = [r for r in pool if r["archetype"] == archetype]
        pool = same + [r for r in pool if r["archetype"] != archetype]
    return pool[:k]


