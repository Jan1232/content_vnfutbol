def format_dna() -> str:
    return FORMAT_DNA


def get_fewshot(archetype: str, k: int = 3) -> list[dict]:
    return _get_fewshot(archetype, k)


def format_fewshot_block(archetype: str, k: int = 3) -> str:
    """Стабильный блок few-shot для кеширования в системном промпте."""
    examples = get_fewshot(archetype, k)
    lines = ["Примеры стиля канала (эталон):"]
    for i, ex in enumerate(examples, 1):
        lines.append(f"\n--- Пример {i} ---")
        lines.append(f"Факт: {ex['fact']}")
        lines.append(f"Достоверность: {ex['veracity']}, сенсация: {ex['is_sensation']}")
        lines.append(f"Пост:\n{ex['post']}")
    return "\n".join(lines)


def format_tone_counterexamples(archetype: str, k: int = 3) -> str:
    """Пары «перебор → как надо» из tone_reference для Producer."""
    examples = [ex for ex in get_tone_examples(archetype, k=8) if ex.get("bad")][:k]
    lines = ["Калибровка тона (так НЕ надо → так надо):"]
    for i, ex in enumerate(examples, 1):
        lines.append(f"\n--- Контрпример {i} ({ex['archetype']}) ---")
        lines.append(f"ПЕРЕБОР:\n{ex['bad']}")
        lines.append(f"КАК НАДО:\n{ex['good']}")
        if ex.get("note"):
            lines.append(f"Почему: {ex['note']}")
    return "\n".join(lines)
