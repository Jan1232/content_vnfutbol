def normalize_for_profanity(text: str) -> str:
    t = unicodedata.normalize("NFKC", text or "")
    t = t.casefold()
    t = t.translate(_CHAR_MAP)
    t = re.sub(r"([а-яa-z])\1+", r"\1", t)
    return t


def _latin_fold(text: str) -> str:
    t = unicodedata.normalize("NFKC", text or "").casefold().replace("ё", "е")
    t = re.sub(r"([a-z])\1+", r"\1", t)
    return t


def _compact_masks(text: str) -> str:
    """п*здец / п0здец → пздец, чтобы корень «пзд» сработал."""
    return re.sub(r"(?<=[а-яa-z])[\W_0-9]+(?=[а-яa-z])", "", text)


def find_profanity(text: str | None) -> str | None:
    """Первый мат в тексте или None."""
    raw = text or ""
    if not raw.strip():
        return None
    cyr = normalize_for_profanity(raw)
    folded = unicodedata.normalize("NFKC", raw).casefold().replace("ё", "е")
    cyr_compact = _compact_masks(cyr)
    # цифры как маска: п0здец — до замены 0→о
    cyr_digit_compact = normalize_for_profanity(_compact_masks(folded))
    latin = _latin_fold(raw)
    latin_compact = _compact_masks(latin)
    for rx, hay in (
        (_CYR_ROOT_RE, cyr),
        (_CYR_ROOT_RE, cyr_compact),
        (_CYR_ROOT_RE, cyr_digit_compact),
        (_CYR_WHOLE_RE, cyr),
        (_CYR_WHOLE_RE, cyr_compact),
        (_HER_RE, cyr),
        (_HER_RE, cyr_compact),
        (_LATIN_ROOT_RE, latin),
        (_LATIN_ROOT_RE, latin_compact),
        (_LATIN_WHOLE_RE, latin),
    ):
        m = rx.search(hay)
        if m:
            return (m.group(0) or "").strip()[:40]
    return None


def contains_profanity(text: str | None) -> bool:
    return find_profanity(text) is not None


