def strip_links_and_cta(text: str) -> str:
    """Вырезает URL и строки с призывом подписаться / CTA (режим strip)."""
    if not text:
        return text
    t = MD_LINK_RE.sub(lambda m: (m.group(1) or "").strip(), text)
    t = URL_RE.sub("", t)
    t = STRIP_BARE_LINK_RE.sub("", t)
    lines: list[str] = []
    for line in t.splitlines():
        s = line.strip()
        if not s:
            lines.append("")
            continue
        if LINK_REG_CTA_LINE_RE.search(s):
            continue
        if STRIP_SIGNATURE_LINE_RE.match(s):
            continue
        # одиночные ‼️ / ⚠️ без текста — хвост после вырезания CTA
        if re.fullmatch(
            r"(?iu)[\s‼️❗⚠⚠️❗️▶️👉⬇️⬇👇🔗]*",
            s,
        ):
            continue
        # хвост после вырезания ссылки: «⚠️Подписаться на RV: MAX |»
        s2 = re.sub(r"(?iu)\bподписаться\s+на\s+rv\b.*$", "", s).strip()
        s2 = re.sub(r"\s*[|｜]\s*$", "", s2).strip(" |｜⚠️")
        s2 = re.sub(r"[ \t]{2,}", " ", s2).strip()
        # «Be inspired…» / «Подробно на нашем сайте» после вырезания URL
        s2 = re.sub(
            r"(?iu)\b(?:"
            r"be\s+inspired\s+by\s+progress|"
            r"watch\s+the\s+full\s+film|"
            r"watch\s+(?:now|here)|"
            r"learn\s+more|find\s+out\s+more|read\s+more|"
            r"узнать\s+больше|подробнее(?:\s+(?:тут|здесь|на\s+(?:нашем\s+)?сайте))?|"
            r"подробно\s+на\s+(?:нашем\s+)?сайте|"
            r"(?:читайте|читай|читать)\s+(?:тут|здесь|подробнее)|"
            r"профиль\s+игрока|протокол\s+матча|"
            r"статистика(?:\s+\S+){0,6}\s+на\s+(?:нашем\s+)?сайте|"
            r"смотрите\s+(?:на\s+)?(?:нашем\s+)?сайте|"
            r"читайте\s+(?:на\s+)?(?:нашем\s+)?сайте"
            r")\s*:?\s*$",
            "",
            s2,
        ).strip(" :")
        if not s2 or s2.casefold() in {
            "max",
            "telegram",
            "телеграм",
            "телеграмм",
            "тг",
            "в max",
            "в telegram",
            "в телеграм",
            "ссылка",
            "ссылка 👉",
            "link",
            "link 👉",
            "⚠️",
            "|",
            "｜",
        }:
            continue
        # «Ссылка 👉» / «Link 👉» после вырезания URL
        if re.match(
            r"(?iu)^\s*(?:ссылк\w*|link)\s*(?:👉[\U0001F3FB-\U0001F3FF]?|➡️|➡|⬇️|⬇|👇)?\s*$",
            s2,
        ):
            continue
        if LINK_REG_CTA_LINE_RE.search(s2):
            continue
        if STRIP_SIGNATURE_LINE_RE.match(s2):
            continue
        lines.append(s2)
    t = "\n".join(lines)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def has_publishable_media(media: list[dict[str, Any]] | None) -> bool:
    """Есть ли в посте фото или видео (для require_media)."""
    for item in media or []:
        if not isinstance(item, dict):
            continue
        if (item.get("type") or "").lower() in {"image", "video"}:
            return True
    return False


def scrub_promo_media(media: list[dict[str, Any]] | None) -> list[dict[str, Any]]:
    """В strip-режиме убираем CTA-кнопки из tg_meta (опросы оставляем)."""
    if not media:
        return []
    out: list[dict[str, Any]] = []
    for item in media:
        if not isinstance(item, dict):
            continue
        if item.get("type") != "tg_meta":
            out.append(item)
            continue
        meta = dict(item)
        meta["buttons"] = []
        # пересылка сама по себе не реклама — оставляем, без кнопок
        out.append(meta)
    return out


def is_advertisement(
    text: str,
    media_urls: list[dict[str, Any]] | list[str] | None = None,
    extra_words: list[str] | None = None,
    *,
    mode: str = "strip",
) -> FilterResult:
    """Считает пост рекламой: слова, ссылки, промо чужих каналов/WhatsApp.

    mode=strip (ядро) — усиленные правила промо/CTA/тизеров;
                 голые URL не блокируют (вырезаются при публикации);
                 словарь слов — HARD.
    mode=strict — то же + блок по любым ссылкам (оверрайд канала).
    """
    raw = text or ""
    lower = raw.casefold()
    strip_mode = (mode or "strip").lower() != "strict"

    media_list: list[dict[str, Any]] = []
    if media_urls:
        for item in media_urls:
            if isinstance(item, dict):
                media_list.append(item)

    # CTA-кнопки / опросы / пересылка+промо — и для strip (до scrub при публикации)
    tg_fr = _check_tg_meta(extract_tg_meta(media_list), raw)
    if tg_fr:
        return tg_fr

    # Урезанный preview t.me/s (копия полного поста с «…» на ~256 символах)
    if is_truncated_tg_preview(raw):
        return FilterResult(True, "обрезанный preview TG")

    words = list(HARD_AD_WORDS if strip_mode else DEFAULT_AD_WORDS)
    if extra_words:
        words.extend(extra_words)

    for w in words:
        if _ad_word_hit(w, raw, lower):
            return FilterResult(True, f"слово: {w}")

    # Единственное отличие strip: URL сами по себе не блок (санитайз вырежет)
    if not strip_mode and (URL_RE.search(raw) or MD_LINK_RE.search(raw)):
        return FilterResult(True, "ссылка в тексте")

    if PROMO_CHANNEL_RE.search(raw):
        return FilterResult(True, "промо каналов")

    if EDU_LEADGEN_RE.search(raw):
        m = EDU_LEADGEN_RE.search(raw)
        return FilterResult(True, f"лидоген-учеба: {(m.group(0) if m else '')[:40]}")

    if CLICKBAIT_PROMO_RE.search(raw):
        return FilterResult(True, "кликбейт+промо")

    if GAMBLING_PROMO_RE.search(raw):
        return FilterResult(True, "беттинг-промо")

    if OFFTOPIC_SPAM_RE.search(raw):
        m = OFFTOPIC_SPAM_RE.search(raw)
        return FilterResult(True, f"оффтоп-спам: {(m.group(0) if m else '')[:40]}")

    if TIPSTER_PROMO_RE.search(raw):
        m = TIPSTER_PROMO_RE.search(raw)
        return FilterResult(True, f"каппер/прогноз: {(m.group(0) if m else '')[:40]}")

    if BET_SLANG_RE.search(raw):
        m = BET_SLANG_RE.search(raw)
        return FilterResult(True, f"ставко-сленг: {(m.group(0) if m else '')[:40]}")

    if TIPSTER_LEADGEN_RE.search(raw):
        m = TIPSTER_LEADGEN_RE.search(raw)
        return FilterResult(True, f"лидоген: {(m.group(0) if m else '')[:40]}")

    if DONATION_PROMO_RE.search(raw):
        m = DONATION_PROMO_RE.search(raw)
        return FilterResult(True, f"донат/сбор: {(m.group(0) if m else '')[:40]}")

