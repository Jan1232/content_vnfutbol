def strip_max_presence_footer(text: str) -> str:
    """Убирает концовку вида «🇷🇺 / ИМЯ в MAX / Мы в MAX 💬»."""
    if not text:
        return text
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    removed = False
    while lines:
        s = lines[-1].strip()
        if not s:
            lines.pop()
            continue
        if (
            _MAX_PRESENCE_LINE_RE.match(s)
            or _SOCIAL_PRESENCE_LINE_RE.match(s)
            or _READ_MORE_LINE_RE.match(s)
            or _DOC_LINK_LEFTOVER_RE.match(s)
        ):
            lines.pop()
            removed = True
            continue
        # флаг/декор сразу перед блоком «в MAX»
        if removed and _FOOTER_DECO_LINE_RE.match(s):
            lines.pop()
            continue
        break
    t = "\n".join(lines)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def strip_social_presence_footers(text: str) -> str:
    """Убирает самопромо соцсетей МИД/посольств/театров.

    Примеры:
    - Web - Telegram - X - Facebook - VK
    - 👉 Телеграм-канал Посольства…
    - 📖 Читайте подробнее… + маркеры порталов
    - 💙 Большой театр ВКонтакте / в MAX
    - 🇷🇺 РОДИОН_МИРОШНИК в MAX / 🦅Минтранс вMAКС
    - 👉 Подробнее о Форуме / Читать подробно
    - 👉 Условия проведения конкурса (хвост после вырезания URL)
    """
    if not text:
        return text
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    out: list[str] = []
    i = 0

    def _pop_trailing_deco() -> None:
        while out and not out[-1].strip():
            out.pop()
        while out and _FOOTER_DECO_LINE_RE.match(out[-1].strip() or ""):
            out.pop()
            while out and not out[-1].strip():
                out.pop()

    def _is_presence_or_cta(s: str) -> bool:
        return bool(
            s
            and (
                _SOCIAL_NAV_LINE_RE.match(s)
                or _TELEGRAM_CHANNEL_LINE_RE.match(s)
                or _SOCIAL_PRESENCE_LINE_RE.match(s)
                or _MAX_PRESENCE_LINE_RE.match(s)
                or _DOC_LINK_LEFTOVER_RE.match(s)
            )
        )

    while i < len(lines):
        s = lines[i].strip()
        if _is_presence_or_cta(s):
            _pop_trailing_deco()
            i += 1
            continue
        if s and _READ_MORE_LINE_RE.match(s):
            _pop_trailing_deco()
            i += 1
            while i < len(lines):
                ns = lines[i].strip()
                if not ns:
                    i += 1
                    continue
                if (
                    _READ_MORE_BULLET_RE.match(ns)
                    or _SOCIAL_NAV_LINE_RE.match(ns)
                    or _DOC_LINK_LEFTOVER_RE.match(ns)
                    or _READ_MORE_LINE_RE.match(ns)
                ):
                    i += 1
                    continue
                break
            continue
        out.append(lines[i])
        i += 1
    _pop_trailing_deco()
    t = "\n".join(out)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def strip_source_signatures(text: str) -> str:
    """Убирает подписи-самопромо канала-источника (строки и хвосты)."""
    if not text:
        return text
    lines = []
    for line in text.splitlines():
        s = line.strip()
        if s and any(rx.match(s) for rx in SOURCE_SIGNATURE_RES):
            continue
        if s:
            s2 = _SOURCE_SIGNATURE_TAIL_RE.sub("", s).strip()
            if not s2:
                continue
            lines.append(s2)
        else:
            lines.append(line)
    t = "\n".join(lines)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def strip_engagement_lines(text: str) -> str:
    """Вырезает вовлечение: «оцените 0–10», «ваши прогнозы», «согласны?» — пост не блокируем."""
    if not text:
        return text
    lines: list[str] = []
    for line in text.splitlines():
        s = line.strip()
        if s and ENGAGEMENT_LINE_RE.match(s):
            continue
        if s:
            s2 = _ENGAGEMENT_TAIL_RE.sub("", s).strip(" .")
            if not s2:
                continue
            lines.append(s2)
        else:
            lines.append(line)
    t = "\n".join(lines)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def strip_hashtags(text: str) -> str:
    """Убирает #хэштеги из текста (строки целиком из тегов — тоже)."""
    if not text:
        return text
    lines: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped and not HASHTAG_RE.sub("", stripped).strip(" .,;:!?-"):
            # строка только из хэштегов — выкидываем
            continue
        line2 = HASHTAG_RE.sub("", line)
        line2 = re.sub(r"[ \t]{2,}", " ", line2).strip(" \t")
        lines.append(line2)
    t = "\n".join(lines)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def sanitize_for_publish(text: str, *, mode: str = "strip") -> str:
    """Правила для всех постов непосредственно перед отправкой в MAX.

    mode=strip (ядро) — вырезает ссылки и строки CTA / «подробнее тут» / «в MAX».
    mode=strict — без вырезки ссылок (редко; оверрайд канала).
    """
    if not text:
        return text
    t = _INSTAGRAM_RE.sub("IG", text)
    t = rewrite_known_handles(t)
    t = strip_promo_attribution_lines(t)
    t = strip_social_presence_footers(t)
    t = strip_max_presence_footer(t)
    t = strip_source_signatures(t)
    t = strip_engagement_lines(t)
    t = strip_social_handles(t)
    t = strip_hashtags(t)
    if (mode or "strip").lower() != "strict":
        t = strip_links_and_cta(t)
    t = re.sub(r"[ \t]{2,}", " ", t)
    t = re.sub(r" *\n *", "\n", t)
    return t.strip()
