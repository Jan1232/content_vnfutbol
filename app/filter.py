def _should_rewrite_handle(key: str, had_at: bool) -> bool:
    """Без @ переписываем только «явные» хэндлы (underscore / *fc / длинные)."""
    if had_at:
        return True
    if "_" in key:
        return True
    if key.endswith(("fc", "cf", "09")):
        return True
    if len(key) >= 12:
        return True
    return False


def rewrite_known_handles(text: str) -> str:
    """@Arsenal_london / Arsenal_london → Арсенал (и аналоги)."""
    if not text:
        return text

    def _sub(m: re.Match[str]) -> str:
        had_at = bool(m.group(1))
        key = m.group(2).casefold()
        name = ENTITY_HANDLES.get(key)
        if not name or not _should_rewrite_handle(key, had_at):
            return m.group(0)
        return name

    return _HANDLE_TOKEN_RE.sub(_sub, text)


