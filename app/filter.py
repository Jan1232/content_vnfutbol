        r"(?iu)\b("
        r"join|channel|канал|whatsapp|подпис|присоединя|"
        r"listen|слуша[йите]|смотри|watch|podcast|spotify|audioboom|"
        r"youtube|youtu\.be|apple\s*podcasts?"
        r")",
