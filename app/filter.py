def _check_tg_meta(meta: dict[str, Any], text: str) -> FilterResult | None:
    """Сигналы из HTML Telegram: пересылка, inline-кнопки, опрос."""
    if not meta:
        return None

    if meta.get("is_poll"):
        return FilterResult(True, "опрос TG")

    buttons = meta.get("buttons") or []
    for btn in buttons:
        label = (btn.get("text") or "").strip()
        url = (btn.get("url") or "").strip().lower()
        if label and TG_BUTTON_CTA_RE.match(label):
            return FilterResult(True, f"кнопка: {label}")
        if label and TEASER_CTA_RE.search(label):
            return FilterResult(True, f"кнопка-тизер: {label}")
        if label and "t.me/" in url:
            return FilterResult(True, f"кнопка-канал: {label}")

    forwarded = (meta.get("forwarded_from") or "").strip()
    if forwarded:
        raw = text or ""
        mentions = AT_MENTION_RE.findall(raw)
        if mentions:
            return FilterResult(True, f"пересылка+@{mentions[0]}")
        if buttons:
            return FilterResult(True, f"пересылка+кнопка ({forwarded})")
        if CTA_HERE_RE.search(raw) or re.search(r"(?iu)👉\s*@", raw):
            return FilterResult(True, f"пересылка+cta ({forwarded})")

    return None


