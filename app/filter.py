def is_cta_here_line(text: str) -> bool:
    """Короткий хвост «смотреть/сезон/скачать … тут» — вырезаем, пост не блокируем."""
    s = (text or "").strip()
    if not s or len(s) > 120:
        return False
    if _CTA_CATCH_RE.match(s):
        return True
    if not (_CTA_END_RE.search(s) or _CTA_START_RE.match(s)):
        return False
    if _CTA_HOOK_RE.search(s):
        return True
    rest = _CTA_END_RE.sub("", s)
    rest = re.sub(r"(?iu)[^\wа-яё]+", "", rest)
    return not rest or bool(_CTA_FILLER_RE.match(rest))


