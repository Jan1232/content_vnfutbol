# Схема/www и «голые» домены (audioboom.com без https:// — частый кейс X/TG).
_BARE_TLD = (
    r"com|net|org|io|co\.uk|ru|me|tv|fm|app|info|biz|online|site|xyz|"
    r"link|shop|blog|news|live|pro|cc|to|podcast|cloud"
)
URL_RE = re.compile(
    r"(?i)\b("
    r"(?:https?://|www\.)[^\s<>\"']+"
    r"|t\.me/[^\s<>\"']+"
    r"|vk\.com/[^\s<>\"']+"
    r"|max\.ru/[^\s<>\"']+"
    r"|wa\.me/[^\s<>\"']+"
    r"|(?:[a-z0-9](?:[a-z0-9\-]{0,61}[a-z0-9])?\.)+(?:" + _BARE_TLD + r")"
    r")",
)
MD_LINK_RE = re.compile(r"\[([^\]]+)\]\((https?://[^)]+)\)")

# Telegram / X @username
AT_MENTION_RE = re.compile(r"(?iu)(?<!\w)@([A-Za-zА-Яа-яЁё0-9_]{3,})")

# #хэштеги (латиница / кириллица)
HASHTAG_RE = re.compile(r"(?iu)(?<!\w)#([A-Za-zА-Яа-яЁё0-9_]+)")

# Стрелки CTA — только целые эмодзи (НЕ character class: иначе [➡️] тянет
# U+FE0F / тон кожи и ловит любой ‼️ / ❤️ как «cta»).
_CTA_ARROW = (
    r"(?:👉[\U0001F3FB-\U0001F3FF]?|➡️|➡|⬇️|⬇|👇|⬆️|⬆|≫|≻)"
)

# кликбейт-CTA: стрелка + HERE / ТУТ / ЗДЕСЬ (слово обязательно)
CTA_HERE_RE = re.compile(
    rf"(?iu){_CTA_ARROW}\s*"
    r"(?:here|тут|сюда|здесь|ссылка|link)",
)

