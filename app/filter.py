def strip_social_handles(text: str) -> str:
    """Убирает @handles: целая строка-тег → удалить; внутри фразы → имя без @."""
    if not text:
        return text
    raw_lines = text.splitlines()
    lines: list[str] = []
    i = 0
    while i < len(raw_lines):
        line = raw_lines[i]
        stripped = line.strip()
        only_handles = AT_MENTION_RE.sub("", stripped).strip(" .,;:!?-")
        is_handle_only = bool(stripped) and (
            AT_MENTION_RE.fullmatch(stripped) is not None
            or (stripped.startswith("@") and not only_handles)
        )
        if is_handle_only:
            names = AT_MENTION_RE.findall(stripped)
            raw_name = names[0] if names else stripped.lstrip("@")
            name = ENTITY_HANDLES.get(raw_name.casefold(), raw_name)
            nxt = raw_lines[i + 1].strip() if i + 1 < len(raw_lines) else ""
            if nxt.startswith("'") and lines:
                lines[-1] = f"{lines[-1].rstrip()} {name}{nxt}"
                i += 2
                continue
            # одиночный @Club на строке → если знаем клуб, вклеиваем имя в предыдущую строку
            if name != raw_name and lines:
                lines[-1] = f"{lines[-1].rstrip()} {name}"
                i += 1
                continue
            i += 1
            continue
        line2 = AT_MENTION_RE.sub(
            lambda m: ENTITY_HANDLES.get(m.group(1).casefold(), m.group(1)),
            line,
        )
        line2 = re.sub(r"[ \t]{2,}", " ", line2).strip(" \t")
        lines.append(line2)
        i += 1
    t = "\n".join(lines)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


