def _fuzzy_root(root: str) -> str:
    return _SEP.join(map(re.escape, root))


def _roots_re(roots: tuple[str, ...]) -> re.Pattern[str]:
    parts = [_fuzzy_root(r) for r in sorted(set(roots), key=len, reverse=True)]
    return re.compile(r"(?iu)(?:" + "|".join(parts) + r")")


